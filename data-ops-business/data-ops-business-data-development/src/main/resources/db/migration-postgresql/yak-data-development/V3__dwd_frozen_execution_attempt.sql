-- R12-3: append-only execution attempts; do not mutate the applied V1/V2.
-- Runtime result is NOT evidence of target-row reconciliation.
CREATE TABLE yak_dev_dwd_execution_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    binding_id BIGINT NOT NULL,
    binding_digest CHAR(64) NOT NULL,
    request_key VARCHAR(36) NOT NULL,
    attempt_digest CHAR(64) NOT NULL,
    state VARCHAR(32) NOT NULL,
    runtime_execution_id VARCHAR(256),
    runtime_status VARCHAR(32),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_dwd_attempt_project_key UNIQUE (project_id, request_key)
);
CREATE INDEX idx_dwd_attempt_binding ON yak_dev_dwd_execution_attempt (project_id, binding_id);
CREATE INDEX idx_dwd_attempt_runtime ON yak_dev_dwd_execution_attempt (project_id, runtime_execution_id);
