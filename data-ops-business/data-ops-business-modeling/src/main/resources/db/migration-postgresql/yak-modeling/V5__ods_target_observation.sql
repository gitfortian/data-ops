-- R11: immutable target Catalog observation; never a deployment receipt.
CREATE TABLE yak_modeling_ods_target_observation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  model_id BIGINT NOT NULL,
  model_version_id BIGINT NOT NULL,
  version_no INTEGER NOT NULL,
  target_datasource_id BIGINT NOT NULL,
  target_database VARCHAR(128) NOT NULL,
  target_schema VARCHAR(128),
  target_table VARCHAR(128) NOT NULL,
  catalog_sha256 CHAR(64) NOT NULL,
  frozen_checksum VARCHAR(64) NOT NULL,
  observed_column_count INTEGER NOT NULL,
  observed_by VARCHAR(128) NOT NULL,
  observed_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);
CREATE INDEX idx_ods_observation_model
  ON yak_modeling_ods_target_observation (project_id, model_id, id);
CREATE INDEX idx_ods_observation_target
  ON yak_modeling_ods_target_observation (project_id, target_datasource_id, id);
